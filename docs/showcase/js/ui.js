    rows([['Производство', made + ' Е/с'], ['Потребление', used + ' Е/с'], ['В запасе', stored], ['Хватает', made >= used ? 'да' : 'нет, машины замедлены на ' + Math.round((1 - made / used) * 100) + '%']],
      note || 'Баланс всей цепи, к которой подключён блок: сколько она производит и тратит, сколько энергии в накопителях и хватает ли её.');

