  const MARK = {
    ok: ['.......', '......#', '.....##', '#...##.', '##.##..', '.###...', '..#....'],
    warn: ['...#...', '..###..', '..###..', '..###..', '...#...', '.......', '...#...'],
    bad: ['##...##', '###.###', '.#####.', '..###..', '.#####.', '###.###', '##...##'],
    // the turret's roles: a sight for attack, a cross for support
    aim: ['...#...', '.#####.', '.#...#.', '###.###', '.#...#.', '.#####.', '...#...'],
    aid: ['..###..', '..###..', '#######', '#######', '#######', '..###..', '..###..'],
  };
  const mark = (kind) => '<svg viewBox="0 0 7 7" shape-rendering="crispEdges" aria-hidden="true">' +
    MARK[kind].map((row, y) => [...row].map((c, x) => (c === '#' ? '<rect x="' + x + '" y="' + y + '" width="1" height="1" fill="currentColor"/>' : '')).join('')).join('') + '</svg>';
  const SEVERITY = { ok: 'работает', warn: 'работает хуже', bad: 'стоит' };
  const status = (text, kind, note) =>
    part('w-wide w-st', '<div class="w-status ' + (kind || 'ok') + '" title="' + SEVERITY[kind || 'ok'] + '">' + mark(kind || 'ok') + '<span>' + text + '</span></div>',
      note || 'Строка состояния. Если блок не работает, здесь написан диагноз.');
  const rows = (pairs, note) => part('w-wide', pairs.map(([k, v]) => '<div class="w-kv"><span>' + k + '</span><b>' + v + '</b></div>').join(''), note);
  // Choices: pages and tabs are tabs over the content; the rest are toggles.
  const TABS = new Set(['Вкладки', 'Страницы']);
  const chips = (label, list, note) => part('w-wide', lab(label) + (TABS.has(label)
    ? '<div class="w-tabs">' + list.map(([t, on]) => '<span' + (on ? ' class="on"' : '') + '>' + t + '</span>').join('') + '</div>'
    : '<div class="w-row">' + list.map(([t, on]) => '<span class="w-tog' + (on ? ' on' : '') + '">' + t + '</span>').join('') + '</div>'), note);
  const raw = (html, note, cls) => part(cls == null ? 'w-wide' : cls, html, note);
  const GLASS = '<svg viewBox="0 0 7 7" shape-rendering="crispEdges" aria-hidden="true"><path d="M1 0h3v1H1zM0 1h1v3H0zM4 1h1v3H4zM1 4h3v1H1zM4 4h1v1H4zM5 5h1v1H5zM6 6h1v1H6z" fill="currentColor"/></svg>';
  // A text field with what is typed and the caret: the terminal's search, the station's name.
  const field = (label, typed, search) => '<div class="w-find">' + (search ? GLASS : '') + '<em>' + label + ':</em> ' + typed + '<i class="w-caret"></i></div>';
  // Energy balance of the whole circuit: what it makes, what it uses, what is stored, and whether it is enough.
